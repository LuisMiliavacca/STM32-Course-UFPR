void Print8x8(int letra, int linha){ //escreve a linha para a letra desejada na matriz de led
	GPIOC->ODR |= 0x00FF;             // Seleção da linha
	GPIOC->ODR &= 0xF0FF;             //
	GPIOB->ODR &= 0x00FF;             // Segmentos -> PB8 a PB15
	GPIOB->ODR |= letras[letra][linha] << 8;
	GPIOC->ODR &= ~(0x01 << (7-linha));
}

int flag_red=1,flag_green=0,flag_blue=0,curr7seg=0,flag_conf=0,i_int=1,i_config=1,letra;
float leitura_ADCpercent, leitura_ADC;

void print7seg(int display, int valor, int dp){ //escreve um numero em um 7seg específico
	GPIOB->ODR &= 0x00FF;             // Segmentos -> PB8 a PB15
	GPIOB->ODR |= seg7[valor] << 8;
	GPIOB->ODR |= (dp & 0x01) << 15;
	GPIOC->ODR &= 0xF0FF;             // Seleção do display -> PC8 a PC11
	GPIOC->ODR |= disp7seg[display] << 8;
}

void escrevefloat(float valor){ //escreve um numero float nos display 7seg
	int valorINT,algarismos[4],ponto;
	valor=valor*10;
	valorINT=(int)valor;
	algarismos[3]=valorINT/1000;
	algarismos[2]=(valorINT%1000)/100;
	algarismos[1]=((valorINT%1000)%100)/10;
	algarismos[0]=((valorINT%1000)%100)%10; //separa os 3 primeiros algarismos mais a priemira casa decimal
	if(curr7seg==1){
		ponto=1;
	}
	else{
		ponto=0;
	}

	print7seg(curr7seg, algarismos[curr7seg], ponto); //escreve o valor no 7seg
}

void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin){
	if((GPIO_Pin & (0x0010))){ //se botão apertado, incrementa i_int e seleciona a cor desejada
		i_int=i_int+1;
		if(i_int==4){
			i_int=1;
		}
		if(i_int==1){
			flag_red=1;
			flag_green=0;
			flag_blue=0;
		}
		if(i_int==2){
			flag_red=0;
			flag_green=1;
			flag_blue=0;
		}
		if(i_int==3){
			flag_red=0;
			flag_green=0;
			flag_blue=1;
		} //seta as flags para cada modo
	}
}
