int linha=0;
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim){
	if(htim->Instance == TIM4){ //interrupção para atualizar o display e a matriz de led
		if(flag_conf){
			if(curr7seg < 4)
			{
				GPIOC->ODR |= 0xFF;
				escrevefloat(leitura_ADCpercent); //escreve o valor da leitura do ADC%
				curr7seg++;
			}else{
				GPIOC->ODR &= 0x00FF;
				if(flag_red){
					Print8x8(0,linha);
					linha++;
				}
				if(flag_green){
					Print8x8(1,linha);
					linha++;
				}
				if(flag_blue){
					Print8x8(2,linha); //escreve em cada linha da matriz de led
					linha++;
				}
				if(linha==8){
					linha=0;
					curr7seg = 0;
				}
			}
		}
		else{
			GPIOC->ODR |= 0xFF;
			escrevefloat(0);
			if(++curr7seg>=4)
				curr7seg = 0;
		}
	}
	if(htim->Instance == TIM3){ //interrupção para ler o valor ADC e setar a flag de configuração
		HAL_ADC_Start_IT(&hadc1); //da trigger na interrupção do timer para fazer leiura
		if((GPIOB -> IDR & 0x0004)==0){
			i_config=i_config+1;
		}
		else{
			i_config=1;
		}
		if(i_config==150){ //seta a flag de configuração como 1 quando passar o tempo estipulado
			flag_conf=1;
		}
	}
}

